    private void listaDesbravadoresMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_listaDesbravadoresMouseClicked
        // TODO add your handling code here:

        if (evt.getClickCount() == 2) {
            int index = listaDesbravadores.getSelectedIndex();

            if (index != 1) {
                JSONArray array = controller.DesbravadorController.mostrarUsuarios(); //JSONArray é equivalente de ArrayList
                JSONObject selecionado = array.getJSONObject(index); //JSONOBject == objeto 

                
                javax.swing.JFrame janela = (javax.swing.JFrame) javax.swing.SwingUtilities.getWindowAncestor(this);

                Desbravador telaDesbravador = new Desbravador(selecionado);
                janela.getContentPane().removeAll(); 
                janela.getContentPane().add(telaDesbravador);
                janela.pack();
                janela.setLocationRelativeTo(null);
                janela.revalidate();
                janela.repaint();
            }

        }
    }//GEN-LAST:event_listaDesbravadoresMouseClicked

